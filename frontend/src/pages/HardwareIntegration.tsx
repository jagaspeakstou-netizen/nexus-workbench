import { useEffect, useState } from "react";
import { fetchHardwareReport, ApiError } from "../services/api";
import type { HwReport, HwTypeGroup } from "../types/hardware";

type LoadState =
  | { kind: "loading" }
  | { kind: "error"; message: string }
  | { kind: "ready"; data: HwReport };

const TYPE_LABELS: Record<string, string> = {
  microcontroller: "Microcontroller",
  fpga: "FPGA",
  jtag: "JTAG Probe",
};

export default function HardwareIntegration() {
  const [state, setState] = useState<LoadState>({ kind: "loading" });
  const [runCount, setRunCount] = useState(0);

  useEffect(() => {
    let cancelled = false;
    setState({ kind: "loading" });
    fetchHardwareReport()
      .then((data) => {
        if (!cancelled) setState({ kind: "ready", data });
      })
      .catch((err) => {
        if (!cancelled) {
          setState({ kind: "error", message: err instanceof ApiError ? err.message : "Unknown error" });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [runCount]);

  if (state.kind === "loading") {
    return (
      <div className="p-8">
        <h1 className="text-2xl font-semibold text-white">Hardware Integration</h1>
        <div className="mt-6 text-sm text-nexus-muted">Running the mock discovery/connect/telemetry sequence…</div>
      </div>
    );
  }
  if (state.kind === "error") {
    return (
      <div className="p-8">
        <h1 className="text-2xl font-semibold text-white">Hardware Integration</h1>
        <div className="mt-6 rounded-lg border border-red-500/30 bg-red-500/10 p-4 text-sm text-red-300">
          <div className="font-medium">Backend unreachable</div>
          <div className="mt-1 text-red-300/80">{state.message}</div>
        </div>
      </div>
    );
  }

  const { data } = state;

  return (
    <div className="p-8 max-w-6xl">
      <div className="flex items-start justify-between">
        <div>
          <h1 className="text-2xl font-semibold text-white">Hardware Integration</h1>
          <p className="text-nexus-muted mt-1 text-sm">
            Mock adapters for three device classes — discovery, a connect handshake with
            scripted retry, and telemetry sampling with a simulated mid-session dropout and
            automatic recovery.
          </p>
        </div>
        <button
          onClick={() => setRunCount((c) => c + 1)}
          className="shrink-0 px-3 py-1.5 rounded text-sm border border-nexus-accent2 text-nexus-accent2 hover:bg-nexus-accent2/10"
        >
          Re-run sequence
        </button>
      </div>

      <div className="mt-4 rounded-lg border border-amber-500/30 bg-amber-500/10 p-3 text-xs text-amber-300">
        {data.mock_disclaimer} Discovery returns a fixed catalog, connect/telemetry timing is
        deterministically seeded by device id (not random) so every run is reproducible — see{" "}
        <code>docs/architecture/hardware_mocks.md</code> for exactly what's simulated and why.
      </div>

      <div className="mt-6 rounded-lg border border-nexus-border bg-nexus-panel p-4">
        <div className="text-xs text-nexus-muted uppercase tracking-wide mb-3">
          Adapter architecture (block diagram)
        </div>
        <BlockDiagram />
      </div>

      {data.types.map((group) => (
        <TypeSection key={group.type} group={group} />
      ))}

      <div className="mt-6 text-xs text-nexus-muted">
        Raw CSVs (per-device telemetry traces, pin tables) generated by{" "}
        <code>nexus_hardware_export</code> and committed under <code>results/csv/</code>.
      </div>
    </div>
  );
}

function TypeSection({ group }: { group: HwTypeGroup }) {
  return (
    <div className="mt-8">
      <h2 className="text-lg font-semibold text-white mb-3">{TYPE_LABELS[group.type] ?? group.type}</h2>

      <div className="grid grid-cols-2 gap-4">
        {group.devices.map((entry) => (
          <div key={entry.device.id} className="rounded-lg border border-nexus-border bg-nexus-panel p-4">
            <div className="flex items-center justify-between">
              <div>
                <div className="text-white font-medium">{entry.device.label}</div>
                <div className="text-xs text-nexus-muted mt-0.5">
                  {entry.device.id} · {entry.device.interface} · {entry.device.vendor}
                </div>
              </div>
              <span
                className={`text-xs px-2 py-0.5 rounded shrink-0 ${
                  entry.connect.connected ? "bg-emerald-500/15 text-emerald-300" : "bg-red-500/15 text-red-300"
                }`}
              >
                {entry.connect.connected ? "CONNECTED" : "FAILED"}
              </span>
            </div>

            <div className="mt-3 text-xs text-nexus-muted">
              Connect attempts:
              <div className="mt-1 flex gap-1.5 flex-wrap">
                {entry.connect.attempts.map((a) => (
                  <span
                    key={a.attempt_number}
                    className={`px-2 py-0.5 rounded font-mono ${
                      a.outcome === "connected"
                        ? "bg-emerald-500/15 text-emerald-300"
                        : "bg-amber-500/15 text-amber-300"
                    }`}
                    title={`${a.simulated_latency_ms.toFixed(1)} ms simulated latency`}
                  >
                    #{a.attempt_number} {a.outcome}
                  </span>
                ))}
              </div>
            </div>

            {entry.telemetry && (
              <div className="mt-3">
                <div className="text-xs text-nexus-muted flex items-center gap-3">
                  <span>{entry.telemetry.samples.length} telemetry samples</span>
                  <span className={entry.telemetry.dropout_count > 0 ? "text-amber-300" : ""}>
                    {entry.telemetry.dropout_count} dropout(s)
                  </span>
                  <span className={entry.telemetry.recovery_count > 0 ? "text-emerald-300" : ""}>
                    {entry.telemetry.recovery_count} recovery(ies)
                  </span>
                </div>
                <div className="mt-2 overflow-x-auto">
                  <table className="text-xs w-full">
                    <thead className="text-nexus-muted">
                      <tr className="text-left">
                        <th className="pr-3 py-1">#</th>
                        <th className="pr-3 py-1">t (s)</th>
                        <th className="pr-3 py-1">V</th>
                        <th className="pr-3 py-1">°C</th>
                        <th className="pr-3 py-1">Lock</th>
                        <th className="pr-3 py-1">Note</th>
                      </tr>
                    </thead>
                    <tbody>
                      {entry.telemetry.samples.slice(0, 8).map((s) => (
                        <tr
                          key={s.sample_index}
                          className={s.note ? "bg-amber-500/10" : undefined}
                        >
                          <td className="pr-3 py-0.5 text-nexus-muted font-mono">{s.sample_index}</td>
                          <td className="pr-3 py-0.5 text-nexus-muted font-mono">{s.timestamp_s.toFixed(2)}</td>
                          <td className="pr-3 py-0.5 text-nexus-muted font-mono">{s.voltage_v.toFixed(3)}</td>
                          <td className="pr-3 py-0.5 text-nexus-muted font-mono">{s.temperature_c.toFixed(2)}</td>
                          <td className="pr-3 py-0.5">{s.clock_locked ? "✓" : "✗"}</td>
                          <td className="pr-3 py-0.5 text-amber-300">{s.note}</td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                  <div className="text-nexus-muted mt-1">
                    showing first 8 of {entry.telemetry.samples.length} — full trace in the committed CSV
                  </div>
                </div>
              </div>
            )}
          </div>
        ))}
      </div>

      <div className="mt-4 rounded-lg border border-nexus-border bg-nexus-panel p-4">
        <div className="text-xs text-nexus-muted uppercase tracking-wide mb-2">
          Pin / voltage table — {TYPE_LABELS[group.type] ?? group.type}
        </div>
        <table className="w-full text-sm">
          <thead className="text-nexus-muted text-xs">
            <tr className="text-left border-b border-nexus-border">
              <th className="px-3 py-1.5">Pin</th>
              <th className="px-3 py-1.5">Function</th>
              <th className="px-3 py-1.5">Voltage</th>
              <th className="px-3 py-1.5">Direction</th>
            </tr>
          </thead>
          <tbody>
            {group.pinout.map((p, i) => (
              <tr key={`${p.name}-${i}`} className="border-b border-nexus-border/50">
                <td className="px-3 py-1.5 text-white font-mono">{p.name}</td>
                <td className="px-3 py-1.5 text-nexus-muted">{p.function}</td>
                <td className="px-3 py-1.5 text-nexus-muted font-mono">{p.voltage_v.toFixed(2)} V</td>
                <td className="px-3 py-1.5 text-nexus-muted">{p.direction}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

